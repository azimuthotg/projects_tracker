# ── ตัวช่วยจัดรูปแบบ ────────────────────────────────────────────────────────

def thai(run, size=BODY, bold=False):
    """กำหนดฟอนต์ไทยและสีดำให้กับข้อความ"""
    run.font.name = FONT
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.append(rfonts)
    for attr in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rfonts.set(qn(attr), FONT)
    run.font.size = Pt(size)
    run.font.bold = bold
    # ขนาดฟอนต์สำหรับอักษร complex script (ไทย) ต้องกำหนดแยก
    szcs = OxmlElement('w:szCs')
    szcs.set(qn('w:val'), str(int(size * 2)))
    rpr.append(szcs)
    if bold:
        bcs = OxmlElement('w:bCs')
        rpr.append(bcs)
    return run


def setup(doc):
    """ตั้งค่าหน้ากระดาษ A4 และฟอนต์เริ่มต้น"""
    for s in doc.sections:
        s.page_height = Cm(29.7)
        s.page_width = Cm(21.0)
        s.left_margin = Cm(2.5)
        s.right_margin = Cm(2.0)
        s.top_margin = Cm(2.5)
        s.bottom_margin = Cm(2.0)

    normal = doc.styles['Normal']
    normal.font.name = FONT
    normal.font.size = Pt(BODY)
    normal.element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    normal.element.rPr.rFonts.set(qn('w:cs'), FONT)

    # ใช้ Heading style เพื่อให้สารบัญอัตโนมัติทำงาน แต่บังคับให้เป็นสีดำ
    for name, size in (('Heading 1', 20), ('Heading 2', 18), ('Heading 3', 16)):
        st = doc.styles[name]
        st.font.name = FONT
        st.font.size = Pt(size)
        st.font.bold = True
        st.font.color.rgb = None
        rpr = st.element.get_or_add_rPr()
        rf = rpr.find(qn('w:rFonts'))
        if rf is None:
            rf = OxmlElement('w:rFonts')
            rpr.append(rf)
        for attr in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
            rf.set(qn(attr), FONT)
        color = OxmlElement('w:color')
        color.set(qn('w:val'), '000000')
        rpr.append(color)
        szcs = OxmlElement('w:szCs')
        szcs.set(qn('w:val'), str(size * 2))
        rpr.append(szcs)


def footer_page_number(doc):
    """ใส่เลขหน้าไว้กึ่งกลางท้ายกระดาษ"""
    for section in doc.sections:
        p = section.footer.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run()
        thai(run, size=14)
        fld = OxmlElement('w:fldSimple')
        fld.set(qn('w:instr'), 'PAGE')
        run._element.addnext(fld)


def h1(doc, text):
    doc.add_page_break()
    p = doc.add_paragraph(style='Heading 1')
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(10)
    thai(p.add_run(text), size=20, bold=True)
    return p


def h2(doc, text):
    p = doc.add_paragraph(style='Heading 2')
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(6)
    thai(p.add_run(text), size=18, bold=True)
    return p


def h3(doc, text):
    p = doc.add_paragraph(style='Heading 3')
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(4)
    thai(p.add_run(text), size=16, bold=True)
    return p


def para(doc, text, indent=0.0, bold=False, space_after=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.left_indent = Cm(indent)
    thai(p.add_run(text), bold=bold)
    return p


def steps(doc, items):
    """ลำดับขั้นตอน — พิมพ์เลขลำดับเอง ไม่ใช้ list style เพื่อให้แปลงเป็น PDF ได้ถูกต้อง"""
    for i, text in enumerate(items, start=1):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(1.5)
        p.paragraph_format.first_line_indent = Cm(-0.9)
        p.paragraph_format.space_after = Pt(4)
        thai(p.add_run(f'{i}.'), bold=True)
        thai(p.add_run(f'\t{text}'))


def shade(cell, hex_color):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tcpr.append(shd)


def table(doc, headers, rows, widths=None, center_cols=()):
    """ตารางหัวเทาอ่อนจัดกึ่งกลาง เนื้อหาสีดำ"""
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER

    for i, text in enumerate(headers):
        cell = t.rows[0].cells[i]
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        thai(p.add_run(text), size=BODY - 1, bold=True)
        shade(cell, HEAD_SHADE)

    for r, row in enumerate(rows, start=1):
        for c, text in enumerate(row):
            cell = t.rows[r].cells[c]
            p = cell.paragraphs[0]
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            if c in center_cols:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            thai(p.add_run(str(text)), size=BODY - 1)

    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)

    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def img(doc, filename, caption):
    """แทรกภาพ 16:9 พร้อมคำบรรยายใต้ภาพ"""
    path = os.path.join(SHOTS, filename)
    if not os.path.exists(path):
        para(doc, f'[ไม่พบไฟล์ภาพ {filename}]')
        return
    _fig[0] += 1
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(path, width=Cm(IMG_W))

    cp = doc.add_paragraph()
    cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cp.paragraph_format.space_after = Pt(12)
    thai(cp.add_run(f'ภาพที่ {_fig[0]}  {caption}'), size=14)


# ── ปกและสารบัญ ────────────────────────────────────────────────────────────

def spacer(doc, count=1):
    """บรรทัดว่างที่ไม่มีระยะห่างเพิ่ม ใช้จัดตำแหน่งบนหน้าปก"""
    for _ in range(count):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(0)


def cover(doc):
    spacer(doc, 4)
    for text, size, bold in (
        ('คู่มือการใช้งาน', 30, True),
        ('ระบบติดตามแผนงาน โครงการและงบประมาณ', 24, True),
    ):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(6)
        thai(p.add_run(text), size=size, bold=bold)

    spacer(doc, 1)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai(p.add_run('สำหรับเจ้าหน้าที่ผู้ปฏิบัติงาน'), size=18)

    spacer(doc, 5)
    for text, size in (
        ('สำนักวิทยบริการ มหาวิทยาลัยนครพนม', 18),
        ('https://lib.npu.ac.th/projects/', 16),
    ):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(4)
        thai(p.add_run(text), size=size)

    spacer(doc, 3)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai(p.add_run('ฉบับปรับปรุง ครั้งที่ 2  |  กรกฎาคม 2569'), size=15)


def toc(doc):
    doc.add_page_break()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(12)
    thai(p.add_run('สารบัญ'), size=22, bold=True)

    p = doc.add_paragraph()
    run = p.add_run()
    thai(run, size=BODY)
    fld = OxmlElement('w:fldSimple')
    fld.set(qn('w:instr'), r'TOC \o "1-2" \h \z \u')
    inner = OxmlElement('w:r')
    t = OxmlElement('w:t')
    t.text = 'สารบัญจะปรากฏเมื่อเปิดเอกสาร'
    inner.append(t)
    fld.append(inner)
    p._p.append(fld)


def update_fields_on_open(doc):
    """สั่งให้ Word และ LibreOffice สร้างสารบัญให้อัตโนมัติตอนเปิดเอกสาร"""
    settings = doc.settings.element
    el = OxmlElement('w:updateFields')
    el.set(qn('w:val'), 'true')
    settings.append(el)


